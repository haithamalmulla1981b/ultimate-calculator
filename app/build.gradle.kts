// Release signing is read from keystore.properties (not committed) or environment variables.
val signingProps = Properties().apply {
    val f = rootProject.file("keystore.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}
fun signingValue(key: String): String? = signingProps.getProperty(key) ?: System.getenv(key.uppercase())

